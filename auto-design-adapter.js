// ── auto-design-adapter.js ───────────────────────────────────────────────────
// The ONLY bridge between the pure solver output and the live three.js scene.
// Imports nothing from main.js; main.js imports from here.
//
// It never holds long-lived references to the walls/placedItems arrays
// (those are reassigned throughout main.js). It only calls the closures in ctx,
// which mutate the real arrays internally.

import { hashSpec } from './auto-design.js';

// Single implementation of the spec hash — re-exported for main.js (save/load).
export { hashSpec };

/**
 * Build walls + cabinets from a solver result into the scene.
 *
 * @param {{walls:Array, cabinets:Array, warnings:Array}} result  solver output
 * @param {object} spec  the wizard spec that produced `result`
 * @param {object} ctx
 *   @param {*}        ctx.THREE             three.js namespace
 *   @param {Function} ctx.buildWall         (startVec3, endVec3, skipHistory) -> wallObj|null
 *   @param {Function} ctx.placeProductAt    (product, {x,y,z}, rotationY) -> mesh|null
 *   @param {Function} ctx.syncOpeningsTo3D  (wallObj) -> void
 *   @param {Array}    ctx.products          product catalogue (Shopify shape)
 * @returns {{builtWalls:Array, placedMeshes:Array, skippedCabinets:Array}}
 */
export function applyAutoDesignResult(result, spec, ctx) {
  const { THREE, buildWall, placeProductAt, syncOpeningsTo3D, products } = ctx;
  const specHash = hashSpec(spec);

  const builtWalls = [];
  const placedMeshes = [];
  const skippedCabinets = [];

  // 1. Walls — skipHistory so the whole generation is one undo entry.
  (result.walls || []).forEach((w, i) => {
    const start = new THREE.Vector3(w.start.x, 0, w.start.z);
    const end = new THREE.Vector3(w.end.x, 0, w.end.z);
    const wallObj = buildWall(start, end, true);   // buildWall pushes to `walls` internally
    if (!wallObj) return;
    wallObj.isCabinetWall = true;
    wallObj.archetypeIndex = i;
    builtWalls.push(wallObj);
  });

  // 2. Openings — convert solver opening shape -> main.js opening shape, then sync.
  (spec.wallAssignments || []).forEach(a => {
    const wallObj = builtWalls[a.wallIndex];
    if (!wallObj || !a.openings || !a.openings.length) return;
    wallObj.openings = a.openings.map(convertOpening);
    syncOpeningsTo3D(wallObj);
  });

  // 3. Cabinets — provenance-stamped at creation.
  (result.cabinets || []).forEach(cab => {
    const product = findProduct(products, cab.productHandle);
    if (!product) {
      skippedCabinets.push({ cabinet: cab, reason: 'sku-not-found' });
      return;
    }
    const mesh = placeProductAt(product, cab.position, cab.rotationY || 0);
    if (!mesh) {
      skippedCabinets.push({ cabinet: cab, reason: 'place-failed' });
      return;
    }
    // ⚠️ NEVER set userData.parentWall — syncOpeningsTo3D() deletes any placed item
    // whose parentWall matches a wall. Use autoWall (serialisable) instead.
    mesh.userData.autoGenerated = true;
    mesh.userData.kitchenRole = cab.kitchenRole || 'drawers';
    mesh.userData.manuallyModified = false;
    mesh.userData.autoWall = { specHash, wallIndex: cab.wallIndex };
    mesh.userData.provenance = {
      source: 'rules',
      confidence: 1.0,
      reference: 'combo-a',
      generatedAt: new Date().toISOString(),
      specHash,
    };
    placedMeshes.push(mesh);
  });

  return { builtWalls, placedMeshes, skippedCabinets };
}

// Solver openings use { positionMm, widthMm, heightMm, sillMm }; the planner's
// opening meshes use { width, height, distFromLeft, floorDist } (all mm).
function convertOpening(o) {
  return {
    type: o.type,
    width: o.widthMm,
    height: o.heightMm || (o.type === 'window' ? 1000 : 2040),
    distFromLeft: o.positionMm,
    floorDist: o.sillMm != null ? o.sillMm : (o.type === 'window' ? 900 : 0),
  };
}

// Case-insensitive product handle lookup against product.id.
function findProduct(products, handle) {
  if (!handle) return null;
  const h = String(handle).toLowerCase();
  return (products || []).find(p => String(p.id).toLowerCase() === h) || null;
}
